#!/usr/bin/env python3
"""Build the standalone Hebrew prompt from the canonical public skill files."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]

def render():
    skill = (ROOT / 'SKILL.md').read_text(encoding='utf-8').split('---', 2)[2].strip()
    skill = re.sub(r'\[([^\]]+)\]\((?:references|assets)/[^)]+\)', r'\1 (מופיע בהמשך ההודעה)', skill)
    skill = skill.replace('קרא את רצף העבודה (מופיע בהמשך ההודעה) לשלב הרלוונטי.', 'קרא את רצף העבודה המובא בהמשך הודעה זו לשלב הרלוונטי.')
    skill = skill.replace('השתמש בתבנית מצב (מופיע בהמשך ההודעה), רשימת המסמכים (מופיע בהמשך ההודעה) ותבנית הכנת בקשה (מופיע בהמשך ההודעה) לפי הצורך.', 'השתמש במבנה המעקב, ברשימת המסמכים ובתבנית הכנת הבקשה המובאים בהמשך הודעה זו לפי הצורך.')
    intro = '''# ליווי משפחתי לתהליך N-600K — הנחיות לשיחה חדשה

פעל לפי ההנחיות הבאות בשיחה הזו. הטקסט מיועד להעתקה בשלמותו לשיחה חדשה; הוא מכיל את רצף העבודה והתבניות הדרושים ללא התקנת סקיל וללא קריאת קבצים נוספים מהמאגר.

## זמינות כלים, המשכיות ועדכונים

- התחל בסיוע מעשי בעברית ובשאלות המעטות הנחוצות לשלב שלנו. אנחנו מתקדמים במסלול משפחתי קיים; אין צורך להתחיל בהרצאת זכאות כללית.
- בדוק אילו יכולות זמינות בפועל בשיחה: גלישה, קריאת קבצים, שמירה ותזכורות. הטקסט אינו מתקין כלים ואינו מעניק גישה לדואר, למסמכי המשפחה, לחשבונות ממשלתיים או לשיחות קודמות.
- אם אין גלישה או שהמקור הרשמי אינו נגיש, אמור מה לא אומת. בקש מאיתנו להביא את ההוראות או ההודעה הרשמיות הדרושות, והמשך בהכנות שאינן תלויות בהן. אל תציג ידע מזיכרון כאימות עדכני של דרישות, אגרות או זמינות.
- אין להניח שתשמור מצב מעבר לשיחה. בסיום שלב תן סיכום קצר שאפשר להעתיק ולהביא לשיחה הבאה. אם כלי שמירה זמין, שמור רק במרחב פרטי מאושר ובכפוף להרשאות.
- הטקסט שהודבק הוא עותק קבוע. שינויים במאגר אינם מעדכנים את השיחה. כדי לקבל גרסה חדשה, נעתיק מחדש את הקובץ העדכני ונביא איתנו את סיכום המצב הפרטי. אל תטען שבדקת או קיבלת עדכון שלא קראת בפועל.
- אין הגשה אוטומטית, חתימה אוטומטית או טיפול עצמאי בתשלומים. אין מעקב ברקע או תזכורות בלי בקשה מפורשת וכלי שאישר את ביצוען. כפוף תמיד לכללי הבטיחות ולהרשאות של המערכת שבה אתה פועל.
- אנו מבקשים עזרה בארגון ובהכנה; אין הבטחה לתוצאה או תחליף להכרעה רשמית. כשיש שאלה משפטית ממשית שמשנה את הצעד, ברר אותה נקודתית במקור רשמי והפנה לעזרה מקצועית לפי הצורך.

'''
    tracking = '''## מבנה מעקב עצמאי לשיחה

נהל רשומה נפרדת לכל משק בית ולכל ילד, בכינויים בלבד כל עוד אין צורך מאושר בפרטים מלאים:
- משק בית; כינוי הילד; גיל או מועד קריטי; השלב הנוכחי; מקור ותאריך הדיווח.
- תיק סב/סבתא: תפקיד בעל התיק, גישה קיימת או חסרה, היקף הרשאת שימוש ומה כבר מוכן. אין גישה אוטומטית בין קרובים.
- מסמכים משותפים ומסמכי ילד; דרכון וכניסה; לשכה וחלון נסיעה; הודעת USCIS האחרונה והפעולה הנדרשת.
- לכל מסמך: כינוי, למי שייך, סוג, שפה, מקור זמין, מצב תרגום ובדיקה, בעל גישה, מיקום פרטי מאושר, פעולה הבאה, אחראי ותלות.
- לכל משימה: מצב, אחראי, תלות, פעולה הבאה, מועד אם יש ומקורו, אישור אנושי נדרש, ראיית סיום ותאריך בדיקה.
- הפרד בין אזרחות הושלמה, תעודה התקבלה, דרכון הוגש/התקבל, SSN הוגש/כרטיס התקבל, והחזרת מסמכי מקור. אל תשמור מספר SSN.
- מצבים אפשריים: לא ידוע, חסר, טרם התחיל, טיוטה, ממתין לבדיקה, מוכן לפעולה אנושית, ממתין לגורם חיצוני, הושלם, לא רלוונטי, נדחה לבקשתנו. העדר מידע אינו תשובה שלילית.
- סיכום להעברה לשיחה חדשה: מה הושלם ובאיזו ראיה, מה פתוח, ההחלטות שכבר התקבלו, עד שלוש פעולות הבאות ושאלות חוסמות. שמור את הסיכום אצלנו באופן פרטי; אל תעלה אותו למאגר ציבורי.

'''
    return intro + skill + '\n\n' + (ROOT/'references/workflow.md').read_text(encoding='utf-8').strip() + '\n\n' + tracking + (ROOT/'assets/application-draft.md').read_text(encoding='utf-8').strip() + '\n\n' + (ROOT/'references/official-sources.md').read_text(encoding='utf-8').strip() + '\n\n## התשובה הראשונה שלך\n\nשאל עד שלוש שאלות קצרות: מה השלב הנוכחי של כל ילד (בכינוי), אילו מסמכים או תיק משפחתי כבר זמינים לנו, ומה הדבר הקרוב שאנו רוצים לקדם. אם כבר מסרנו את המידע, המשך ממנו בלי לשאול שוב.\n'

if __name__ == '__main__':
    path = ROOT/'CHATGPT-PROMPT.md'
    content = render()
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit('CHATGPT-PROMPT.md is out of date; run python3 scripts/build_chatgpt_prompt.py')
        print('Standalone prompt is synchronized.')
    else:
        path.write_text(content, encoding='utf-8')
        print('Generated CHATGPT-PROMPT.md')
